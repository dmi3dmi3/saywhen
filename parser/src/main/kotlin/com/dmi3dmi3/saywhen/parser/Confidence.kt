package com.dmi3dmi3.saywhen.parser

/**
 * Дискретная шкала специфичности кандидата — часть контракта мерджа, не языка.
 * Транслятор проставляет скор, зная свои формы; арбитраж сравнивает числа,
 * не зная про формы (инкапсуляция: «6:00» vs «шесть» — знание парсера).
 * Дискретность сохраняет детерминизм и дебажимость, которые потерялись бы
 * на континуальных процентах.
 */
internal enum class Confidence(val weight: Int) {
    EXPLICIT(100),  // «6:00», «завтра», «каждый вторник»
    STRONG(70),     // «шесть часов», «пол седьмого», «полдень»
    WEAK(30),       // голый час по смежности («завтра 11 планёрка»)
}
